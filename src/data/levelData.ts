function normalizeLevelHazards(level: LevelData): LevelData {
  return {
    ...level,
    hazards: level.hazards.map((hazard) => {
      if (hazard.y <= 40) {
        return { ...hazard, y: 250 };
      }
      if (hazard.y >= 500) {
        return { ...hazard, y: 300 };
      }
      return hazard;
    }),
  };
}

const ALL_LEVELS: LevelData[] = [
  ...WORLD_1_LEVELS,
  ...WORLD_2_LEVELS,
  ...WORLD_3_LEVELS,
  ...WORLD_4_LEVELS,
  ...WORLD_5_LEVELS,
].map(normalizeLevelHazards);

const levelMap = new Map<number, LevelData>(
  ALL_LEVELS.map((level) => [level.id, level])
);

export function getLevelData(id: number): LevelData | undefined {
  return levelMap.get(id);
}

export function getAllLevelData(): LevelData[] {
  return [...ALL_LEVELS];
}
